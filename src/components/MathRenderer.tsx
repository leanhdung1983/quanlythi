// Smart split function to handle LaTeX delimiters and environments
const smartSplit = (str: string, delimiter: string): string[] => {
    const result: string[] = [];
    let current = '';
    let depth = 0; // tracking nested braces {}
    let inMath = false; // tracking $...$ or $$...$$
    let mathChar = ''; // '$' or '$$'
    let inEnv = 0; // tracking \begin{...} \end{...}

    for (let i = 0; i < str.length; i++) {
        const char = str[i];
        const nextChar = str[i + 1];

        // Handle math mode $ or $$
        if (char === '$' && str[i - 1] !== '\\') {
            if (nextChar === '$') {
                if (inMath && mathChar === '$$') {
                    inMath = false;
                    mathChar = '';
                } else if (!inMath) {
                    inMath = true;
                    mathChar = '$$';
                }
                current += '$$';
                i++;
                continue;
            } else {
                if (inMath && mathChar === '$') {
                    inMath = false;
                    mathChar = '';
                } else if (!inMath) {
                    inMath = true;
                    mathChar = '$';
                }
            }
        }

        // Handle braces
        if (char === '{' && str[i - 1] !== '\\') depth++;
        if (char === '}' && str[i - 1] !== '\\') depth--;

        // Handle environments \begin{...} \end{...}
        if (str.substring(i, i + 7) === '\\begin{') inEnv++;
        if (str.substring(i, i + 5) === '\\end{') inEnv--;

        // Split if delimiter found and we are not in any special mode
        if (char === delimiter && depth === 0 && !inMath && inEnv === 0) {
            result.push(current);
            current = '';
        } else {
            current += char;
        }
    }
    result.push(current);
    return result;
};

// Pre-process lists (enumerate/itemize) to HTML tags for better layout
const formatLatexLists = (text: string): string => {
    let res = text;
    
    // Clean environment wrappers nicely
    res = res.replace(/\\begin\s*\{center\}/gi, '').replace(/\\end\s*\{center\}/gi, '');
    
    // Better list handling that handles nesting by using simple string replacement 
    // and then cleaning up the </li> structure
    
    // 1. Process starts of lists
    res = res.replace(/\\begin\s*\{enumerate\}(?:\[.*?\])?/gi, '<ol class="list-decimal pl-6 space-y-2 my-2">');
    res = res.replace(/\\begin\s*\{(?:itemize|itemchoice)\}(?:\[.*?\])?/gi, '<ul class="list-disc pl-6 space-y-2 my-2">');
    
    // 2. Process ends of lists
    res = res.replace(/\\end\s*\{enumerate\}/gi, '</li></ol>');
    res = res.replace(/\\end\s*\{(?:itemize|itemchoice)\}/gi, '</li></ul>');
    
    // 3. Process items
    // Using a class for <li> to match Tailwind styling
    res = res.replace(/\\item/gi, '</li><li class="mt-1">');
    
    // 4. Cleanup: Remove the first </li> that's generated by the first \item
    // Any <ol...> or <ul...> that is immediately followed by a </li> should have that </li> removed correctly.
    // Also handle possible spaces between them.
    res = res.replace(/(<(ol|ul)[^>]*>)\s*<\/li>/gi, '$1');
    
    // 5. Cleanup: If there's a trailing \item just before \end, it might leave an empty <li></li>
    res = res.replace(/<li[^>]*>\s*<\/(ol|ul)>/gi, '</$1>');

    return res;
};

